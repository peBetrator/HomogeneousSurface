/**
 * Project0.cpp
 *
 * Главный файл приложения визуализации конической однородной поверхности на основе астроиды.
 *
 * Ключевые компоненты:
 * 1. Инициализация GLFW и OpenGL контекста
 * 2. Настройка модели освещения Фонга (Phong) с тремя источниками света
 * 3. Управление камерой (вращение, приближение/удаление)
 * 4. Главный цикл отрисовки с анимацией
 * 5. Обработка пользовательского ввода
 *
 * Управление:
 * - ← → : вращение по горизонтали (Yaw)
 * - ↑ ↓ : вращение по вертикали (Pitch)
 * - PgUp/PgDn : приближение/отдаление (Zoom)
 * - Space : включить/выключить автовращение
 * - R : сброс ориентации камеры
 * - ESC : выход из приложения
 */

// ============================================================
// Подключение библиотек
// ============================================================

// GLFW — кроссплатформенная библиотека для создания окон и обработки ввода
#include <GLFW/glfw3.h>

#include <iostream>  // для вывода ошибок
#include <cmath>     // математические функции

// ============================================================
// Кроссплатформенные заголовки OpenGL
// ============================================================
// macOS использует другие пути для заголовков OpenGL
#ifdef __APPLE__
#include <OpenGL/gl.h>   // основные функции OpenGL
#include <OpenGL/glu.h>  // GLU (OpenGL Utility Library) — gluCylinder, gluBuild2DMipmaps и т.д.
#else
#include <GL/gl.h>       // Windows/Linux
#include <GL/glu.h>
#endif

// ============================================================
// Подключение классов сцены
// ============================================================
#include "CoordinateAxes.hpp"    // система координат XYZ с цветными стрелками
#include "Background.hpp"        // фоновое изображение из BMP
#include "AstroidConeLit.hpp"    // коническая поверхность астроиды с освещением

// ============================================================
// Глобальные объекты сцены
// ============================================================
// static — ограничивает видимость этого файла (локальные глобальные переменные)

static CoordinateAxes gAxes;       // оси координат (X=красная, Y=зелёная, Z=синяя)
static Background gBackground;     // фоновая текстура

// ============================================================
// Геометрия астроиды
// ============================================================
// Параметры конструктора: (levels, segments, depth)
// - levels=12   : количество уровней (колец) от апекса, L ∈ [1, ∞)
// - segments=64 : количество точек на контуре астроиды, S ∈ [3, ∞)
// - depth=3.0   : глубина конуса по оси Z, D ∈ [0, ∞)
//
// Статистика геометрии:
// - Вершин: 1 (apex) + 64×24 = 1537
// - Колец: 24 (12 уровней × 2 половины)
// - Треугольников: ~2944
static AstroidConeLit gAstroid(12, 64, 3.0f);

// ============================================================
// Управление анимацией и камерой
// ============================================================

static GLFWwindow* gWindow = nullptr;  // указатель на окно GLFW

// --- Режим автовращения ---
static bool gSpinEnabled = true;  // включить/выключить автовращение (переключается клавишей Space)

// --- Углы поворота камеры (в градусах) ---
// Yaw (рыскание) — поворот вокруг оси Y (левый/правый)
// Pitch (тангаж) — поворот вокруг оси X (верх/вниз)
static float gYawDeg   = -35.0f;  // начальный Yaw: -35° (сцена повёрнута влево)
static float gPitchDeg =  35.0f;  // начальный Pitch: +35° (сцена наклонена вниз)

// --- Скорость вращения ---
static float gYawSpeedDps = 20.0f;  // автовращение по Yaw: 20 градусов в секунду (DPS = degrees per second)

// --- Время для delta-time ---
// Delta-time — разница времени между кадрами (для плавной анимации независимо от FPS)
static double gLastTime = 0.0;  // время предыдущего кадра (в секундах)

// --- Управление камерой клавишами ---
static float gKeyYawSpeedDps   = 90.0f;  // скорость ручного поворота по Yaw (стрелки ←→): 90°/сек
static float gKeyPitchSpeedDps = 90.0f;  // скорость ручного поворота по Pitch (стрелки ↑↓): 90°/сек

// --- Зум (дистанция камеры) ---
// Камера позиционируется через glTranslated(0, 0, -gCamDist)
// Большее значение = дальше от сцены
static float gCamDist = 6.0f;  // начальная дистанция: 6.0 (можно менять через PgUp/PgDn)

/**
 * Инициализация сцены
 *
 * Настраивает параметры всех объектов сцены:
 * 1. Оси координат (длина, стрелки, толщина линий, сглаживание)
 * 2. Фоновое изображение (загрузка BMP)
 * 3. Геометрия астроиды (построение меша, режим wireframe)
 * 4. Инициализация таймера для анимации
 *
 * Вызывается один раз при запуске приложения (из main()).
 */
void initScene() {
	// ============================================================
	// Настройка осей координат
	// ============================================================
	gAxes.setLength(5.5f);           // длина каждой оси: 5.5 единиц
	gAxes.setArrow(0.1f, 0.2f);      // стрелки: радиус=0.1, высота=0.2
	gAxes.setLineWidth(1.5f);        // толщина линий: 1.5 пикселя
	gAxes.setShowOriginPoint(true);  // показывать белую точку в начале координат (0,0,0)
	gAxes.setLineSmooth(true);       // включить сглаживание линий (GL_LINE_SMOOTH)

	// ============================================================
	// Загрузка фонового изображения
	// ============================================================
	// loadFromExeDir ищет файл относительно папки с исполняемым файлом
	if (!gBackground.loadFromExeDir("assets/background_lion.bmp")) {
		// Если файл не найден, выводим предупреждение (не критично)
		std::cerr << "Warning: Can't load assets/background_lion.bmp" << std::endl;
	}

	// ============================================================
	// Построение геометрии астроиды
	// ============================================================
	// build() генерирует вершины, индексы и вершинные нормали
	gAstroid.build();

	// setWireframe(true) включает отрисовку каркаса (edges) поверх заливки
	// Это помогает увидеть структуру треугольной сетки
	gAstroid.setWireframe(true);

	// ============================================================
	// Инициализация таймера
	// ============================================================
	// glfwGetTime() возвращает время в секундах с момента инициализации GLFW
	// Используется для расчёта delta-time в анимации
    gLastTime = glfwGetTime();
}

/**
 * Обработка изменения размера окна
 *
 * Функция вызывается при:
 * - Создании окна
 * - Изменении размера окна пользователем
 *
 * Задачи:
 * 1. Настройка viewport (области рисования)
 * 2. Настройка матрицы проекции (ортогональная или перспективная)
 *
 * OpenGL матрицы:
 * - GL_PROJECTION — матрица проекции (как 3D проецируется на 2D экран)
 * - GL_MODELVIEW — матрица модели-вида (положение камеры и объектов)
 *
 * @param width  - новая ширина framebuffer в пикселях
 * @param height - новая высота framebuffer в пикселях
 */
void resize(int width, int height)
{
	// ============================================================
	// Настройка Viewport (области рисования)
	// ============================================================
	// glViewport(x, y, width, height) — задаёт прямоугольную область окна для рисования
	// Координаты (x,y) — левый нижний угол
	// Размеры (width, height) — ширина и высота области
	//
	// Здесь создаём квадратную область с отступами 10 пикселей от краёв
	GLuint wp = width < height ? width - 20 : height - 20;  // квадрат (меньшая сторона минус отступы)
	glViewport(10, 10, wp, wp);  // x=10, y=10, размер=(wp × wp)

	// ============================================================
	// Настройка матрицы проекции
	// ============================================================
	// glMatrixMode — выбрать текущую матрицу для последующих операций
	glMatrixMode(GL_PROJECTION);

	// glLoadIdentity — сбросить матрицу в единичную (identity matrix)
	// Единичная матрица = нет трансформаций
	glLoadIdentity();

	// ============================================================
	// Тип проекции
	// ============================================================
	// glOrtho — ортогональная (параллельная) проекция
	// glFrustum — перспективная проекция
	//
	// В ортогональной проекции объекты не уменьшаются с расстоянием (как в CAD)
	// В перспективной проекции дальние объекты меньше (реалистичнее)
	//
	// glOrtho(left, right, bottom, top, near, far)
	// - left, right, bottom, top — границы видимого объёма в плоскости near
	// - near, far — расстояния до ближней и дальней отсекающих плоскостей
	//
	// Координаты:
	// X ∈ [-6.2, 6.2] — ширина 12.4 единицы
	// Y ∈ [-6.2, 6.2] — высота 12.4 единицы
	// Z ∈ [2.0, 12.0] — глубина 10.0 единиц (только объекты в этом диапазоне видны)
	glOrtho(-6.2, 6.2, -6.2, 6.2, 2.0, 12.0);

	// Альтернатива — перспективная проекция (закомментирована):
	// glFrustum(-5.0, 5.0, -5.0, 5.0, 2.0, 12.0);
	// Параметры аналогичны, но создаёт эффект перспективы

	// ============================================================
	// Переключение обратно на матрицу модели-вида
	// ============================================================
	// После настройки проекции переключаемся на MODELVIEW
	// В MODELVIEW работают команды позиционирования камеры и объектов (glTranslate, glRotate)
	glMatrixMode(GL_MODELVIEW);
}

/**
 * Главная функция отрисовки кадра
 *
 * Вызывается каждый кадр в главном цикле приложения.
 *
 * Последовательность рендеринга:
 * 1. Очистка буферов цвета и глубины
 * 2. Отрисовка фонового изображения (2D, экранные координаты)
 * 3. Расчёт delta-time и обновление анимации
 * 4. Обработка пользовательского ввода (клавиши)
 * 5. Настройка камеры (положение и вращение)
 * 6. Установка позиций источников света
 * 7. Отрисовка 3D-сцены (оси координат и астроида)
 *
 * OpenGL функции:
 * - glClear — очистить буферы
 * - glPushMatrix/glPopMatrix — сохранить/восстановить матрицу трансформаций
 * - glTranslated — переместить систему координат
 * - glRotatef — повернуть систему координат
 * - glLightfv — установить параметр источника света
 */
void display(void)
{
    // ============================================================
    // ШАГ 1: Очистка буферов
    // ============================================================
    // glClear очищает указанные буферы перед рисованием нового кадра
    // GL_COLOR_BUFFER_BIT — буфер цвета (пиксели)
    // GL_DEPTH_BUFFER_BIT — буфер глубины (Z-буфер для корректного порядка отрисовки)
    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);

    // ============================================================
    // ШАГ 2: Отрисовка фона
    // ============================================================
    // Фон рисуется в 2D экранных координатах (ортогональная проекция)
    // Background::draw() сам управляет своими состояниями OpenGL
    gBackground.draw();

    // ============================================================
    // ШАГ 3: Расчёт delta-time и анимация
    // ============================================================
    // Delta-time — время, прошедшее с предыдущего кадра (в секундах)
    // Используется для плавной анимации независимо от FPS
    double now = glfwGetTime();  // текущее время (секунды с момента запуска GLFW)
    float dt = (float)(now - gLastTime);  // delta-time (секунды)
    gLastTime = now;  // сохраняем для следующего кадра

    // --- Автовращение (если включено) ---
    if (gSpinEnabled) {
        // Увеличиваем угол Yaw на gYawSpeedDps градусов за секунду
        // dt масштабирует скорость: за dt секунд поворот = gYawSpeedDps * dt градусов
        gYawDeg += gYawSpeedDps * dt;

        // Нормализуем угол в диапазон [-360°, 360°]
        // (предотвращает переполнение при длительной работе)
        if (gYawDeg > 360.f)  gYawDeg -= 360.f;
        if (gYawDeg < -360.f) gYawDeg += 360.f;
    }

    // ============================================================
    // ШАГ 4: Обработка клавиатурного ввода
    // ============================================================
    // glfwGetKey возвращает GLFW_PRESS, если клавиша нажата в текущий момент

    // --- Yaw (поворот влево/вправо, стрелки ← →) ---
    if (glfwGetKey(gWindow, GLFW_KEY_LEFT) == GLFW_PRESS)
        gYawDeg -= gKeyYawSpeedDps * dt;  // влево: уменьшаем Yaw
    if (glfwGetKey(gWindow, GLFW_KEY_RIGHT) == GLFW_PRESS)
        gYawDeg += gKeyYawSpeedDps * dt;  // вправо: увеличиваем Yaw

    // --- Pitch (наклон вверх/вниз, стрелки ↑ ↓) ---
    if (glfwGetKey(gWindow, GLFW_KEY_UP) == GLFW_PRESS)
        gPitchDeg -= gKeyPitchSpeedDps * dt;  // вверх: уменьшаем Pitch
    if (glfwGetKey(gWindow, GLFW_KEY_DOWN) == GLFW_PRESS)
        gPitchDeg += gKeyPitchSpeedDps * dt;  // вниз: увеличиваем Pitch

    // Ограничиваем Pitch в диапазоне [-89°, 89°]
    // (предотвращает "переворот" камеры через полюс)
    if (gPitchDeg > 89.f)  gPitchDeg = 89.f;
    if (gPitchDeg < -89.f) gPitchDeg = -89.f;

    // --- Зум (приближение/отдаление, PgUp/PgDn) ---
    if (glfwGetKey(gWindow, GLFW_KEY_PAGE_UP) == GLFW_PRESS)
        gCamDist -= 3.0f * dt;  // PgUp: приближаемся (уменьшаем дистанцию)
    if (glfwGetKey(gWindow, GLFW_KEY_PAGE_DOWN) == GLFW_PRESS)
        gCamDist += 3.0f * dt;  // PgDn: отдаляемся (увеличиваем дистанцию)

    // Ограничиваем дистанцию камеры в диапазоне [2.5, 12.0]
    // (слишком близко = видим внутри объекта, слишком далеко = объект слишком мал)
    if (gCamDist < 2.5f) gCamDist = 2.5f;
    if (gCamDist > 12.f) gCamDist = 12.f;

    // ============================================================
    // ШАГ 5: Настройка 3D-сцены
    // ============================================================
    glMatrixMode(GL_MODELVIEW);  // работаем с матрицей модели-вида

    // glPushMatrix сохраняет текущую матрицу в стек
    // (позволяет вернуться к исходному состоянию через glPopMatrix)
    glPushMatrix();

    // glLoadIdentity сбрасывает матрицу в единичную (нет трансформаций)
    glLoadIdentity();

    // ============================================================
    // Позиционирование камеры
    // ============================================================
    // glTranslated(x, y, z) — переместить систему координат на вектор (x,y,z)
    // Камера "отодвигается" назад на gCamDist единиц по оси Z
    // (в OpenGL камера смотрит вдоль -Z, поэтому перемещаем на -gCamDist)
    glTranslated(0.0, 0.0, -gCamDist);

    // ============================================================
    // Вращение сцены
    // ============================================================
    // glRotatef(angle, x, y, z) — повернуть на angle° вокруг вектора (x,y,z)
    //
    // Порядок поворотов важен! (матрицы не коммутативны)
    // Сначала Pitch (вокруг X), потом Yaw (вокруг Y)

    // Поворот вокруг оси X (наклон вверх/вниз)
    glRotatef(gPitchDeg, 1.0f, 0.0f, 0.0f);

    // Поворот вокруг оси Y (поворот влево/вправо)
    glRotatef(gYawDeg, 0.0f, 1.0f, 0.0f);

    // ============================================================
    // ШАГ 6: Установка позиций источников света
    // ============================================================
    // ВАЖНО: позиции источников света устанавливаются ПОСЛЕ трансформаций камеры
    // Это делает источники света фиксированными относительно сцены (вращаются вместе с ней)
    //
    // glLightfv(light, pname, params) — установить параметр источника света
    // - light: GL_LIGHT0, GL_LIGHT1, ... — идентификатор источника
    // - pname: GL_POSITION — позиция источника
    // - params: массив [x, y, z, w] — координаты (w=1 для точечного источника, w=0 для направленного)
    {
        // LIGHT0 — тёплый свет сверху справа спереди
        GLfloat pos0[4] = { 3.f, 3.f, 3.f, 1.f };  // (x=3, y=3, z=3, w=1)

        // LIGHT1 — холодный свет сверху слева сзади
        GLfloat pos1[4] = { -3.f, 3.f, -3.f, 1.f };

        // LIGHT2 — фоновый свет снизу сзади
        GLfloat pos2[4] = { 0.f, -3.f, 3.f, 1.f };

        // Устанавливаем позиции всех трёх источников
        glLightfv(GL_LIGHT0, GL_POSITION, pos0);
        glLightfv(GL_LIGHT1, GL_POSITION, pos1);
        glLightfv(GL_LIGHT2, GL_POSITION, pos2);
    }

    // ============================================================
    // ШАГ 7: Восстановление состояний OpenGL
    // ============================================================
    // Background::draw() мог изменить некоторые состояния OpenGL
    // (например, отключить освещение для рисования 2D-текстуры)
    // Здесь восстанавливаем нужные состояния для 3D-рендеринга

    glEnable(GL_DEPTH_TEST);  // включить Z-тест (правильный порядок отрисовки по глубине)
    glEnable(GL_LIGHTING);    // включить освещение (модель Фонга)

    // glShadeModel — выбрать модель затенения
    // GL_SMOOTH (Gouraud) — плавное затенение через интерполяцию вершинных цветов
    // GL_FLAT — плоское затенение (каждый полигон одного цвета)
    glShadeModel(GL_SMOOTH);

    // glPolygonMode — режим отрисовки полигонов
    // GL_FILL — заполненные полигоны (по умолчанию)
    // GL_LINE — только рёбра (wireframe)
    // GL_POINT — только вершины
    glPolygonMode(GL_FRONT_AND_BACK, GL_FILL);

    // ============================================================
    // ШАГ 8: Отрисовка объектов сцены
    // ============================================================
    gAxes.draw();     // оси координат (X=красная, Y=зелёная, Z=синяя)
    gAstroid.draw();  // коническая поверхность астроиды с освещением

    // ============================================================
    // Завершение кадра
    // ============================================================
    // glFlush — принудительно отправить все команды OpenGL на выполнение
    // (обычно команды буферизируются для оптимизации)
    glFlush();

    // glPopMatrix — восстановить матрицу, сохранённую через glPushMatrix
    // (возвращаем матрицу в состояние до всех трансформаций камеры)
    glPopMatrix();
}

// ============================================================
// Обработка клавиш с edge detection (Space и R)
// ============================================================
// Для клавиш Space и R используем "edge detection" (детектирование фронта сигнала)
// Это позволяет срабатывать только при НАЖАТИИ клавиши, а не каждый кадр, пока она зажата
//
// Переменные состояния: true = клавиша была нажата в предыдущем кадре
static bool gSpaceWasPressed = false;  // состояние клавиши Space
static bool gRWasPressed = false;      // состояние клавиши R

/**
 * Обработка клавиш Space и R с edge detection
 *
 * Вызывается каждый кадр из главного цикла.
 *
 * Edge detection (детектирование фронта):
 * - Срабатывает только при ПЕРЕХОДЕ из "не нажата" в "нажата"
 * - Предотвращает многократные срабатывания при удержании клавиши
 *
 * Обрабатываемые клавиши:
 * - Space: переключить автовращение (toggle gSpinEnabled)
 * - R: сбросить ориентацию камеры к начальным значениям
 */
void processKeyCallbacks() {
    // ============================================================
    // Обработка клавиши Space (toggle автовращения)
    // ============================================================
    // glfwGetKey возвращает GLFW_PRESS, если клавиша нажата в текущий момент
    bool spacePressed = (glfwGetKey(gWindow, GLFW_KEY_SPACE) == GLFW_PRESS);

    // Срабатывает только если:
    // - Клавиша нажата СЕЙЧАС (spacePressed == true)
    // - Клавиша НЕ была нажата в ПРЕДЫДУЩЕМ кадре (!gSpaceWasPressed)
    // Это гарантирует, что действие выполнится только один раз при нажатии
    if (spacePressed && !gSpaceWasPressed) {
        // Переключаем флаг автовращения (true -> false или false -> true)
        gSpinEnabled = !gSpinEnabled;
    }

    // Сохраняем текущее состояние для следующего кадра
    gSpaceWasPressed = spacePressed;

    // ============================================================
    // Обработка клавиши R (reset ориентации камеры)
    // ============================================================
    bool rPressed = (glfwGetKey(gWindow, GLFW_KEY_R) == GLFW_PRESS);

    // Аналогично Space — срабатывает только при НАЖАТИИ, а не при удержании
    if (rPressed && !gRWasPressed) {
        // Возвращаем углы камеры к начальным значениям
        gYawDeg = -35.f;   // начальный поворот по горизонтали
        gPitchDeg = 35.f;  // начальный наклон по вертикали
    }

    // Сохраняем текущее состояние для следующего кадра
    gRWasPressed = rPressed;
}

/**
 * GLFW callback для изменения размера framebuffer
 *
 * Автоматически вызывается GLFW при:
 * - Создании окна
 * - Изменении размера окна пользователем
 * - Переходе в полноэкранный режим
 *
 * Делегирует вызов функции resize(), которая настраивает viewport и проекцию.
 *
 * @param window - указатель на окно GLFW
 * @param width  - новая ширина framebuffer в пикселях
 * @param height - новая высота framebuffer в пикселях
 */
void framebuffer_size_callback(GLFWwindow* window, int width, int height) {
    resize(width, height);
}

/**
 * Точка входа в приложение
 *
 * Последовательность инициализации:
 * 1. Инициализация GLFW (библиотека для создания окон и обработки ввода)
 * 2. Создание окна и OpenGL контекста
 * 3. Настройка callback'ов (изменение размера окна)
 * 4. Инициализация сцены (геометрия, текстуры, оси)
 * 5. Настройка глобальных состояний OpenGL (Z-буфер, прозрачность, сглаживание)
 * 6. Настройка освещения (модель Фонга с 3 источниками света)
 * 7. Главный цикл рендеринга
 * 8. Очистка ресурсов и завершение
 *
 * @return 0 при успешном завершении, -1 при ошибке инициализации
 */
int main()
{
    // ============================================================
    // ШАГ 1: Инициализация GLFW
    // ============================================================
    // GLFW (Graphics Library Framework) — кроссплатформенная библиотека для:
    // - Создания окон с OpenGL контекстом
    // - Обработки ввода (клавиатура, мышь)
    // - Управления событиями
    //
    // glfwInit() инициализирует библиотеку
    // Возвращает GLFW_TRUE (1) при успехе, GLFW_FALSE (0) при ошибке
    if (!glfwInit()) {
        std::cerr << "Failed to initialize GLFW" << std::endl;
        return -1;
    }

    // ============================================================
    // ШАГ 2: Настройка параметров окна (hints)
    // ============================================================
    // glfwWindowHint задаёт параметры создаваемого окна
    // Вызывается ДО создания окна

    // Версия OpenGL контекста: 2.1 (legacy OpenGL)
    // Используем старую версию для совместимости с immediate mode (glBegin/glEnd)
    glfwWindowHint(GLFW_CONTEXT_VERSION_MAJOR, 2);  // мажорная версия: 2
    glfwWindowHint(GLFW_CONTEXT_VERSION_MINOR, 1);  // минорная версия: 1

    // MSAA (Multisample Anti-Aliasing) — сглаживание зубчатых краёв
    // 4 samples = 4x MSAA (хорошее качество с приемлемой производительностью)
    glfwWindowHint(GLFW_SAMPLES, 4);

    // ============================================================
    // ШАГ 3: Создание окна
    // ============================================================
    // glfwCreateWindow(width, height, title, monitor, share)
    // - width, height: размер окна в пикселях (500×500)
    // - title: заголовок окна
    // - monitor: nullptr = оконный режим (не полноэкранный)
    // - share: nullptr = не делиться ресурсами с другими контекстами
    //
    // Возвращает указатель на окно или nullptr при ошибке
    gWindow = glfwCreateWindow(500, 500, "OpenGL - Homogeneous Surface", nullptr, nullptr);
    if (!gWindow) {
        std::cerr << "Failed to create GLFW window" << std::endl;
        glfwTerminate();  // освобождаем ресурсы GLFW перед выходом
        return -1;
    }

    // ============================================================
    // ШАГ 4: Активация OpenGL контекста
    // ============================================================
    // glfwMakeContextCurrent делает OpenGL контекст окна текущим для данного потока
    // После этого можно вызывать функции OpenGL (glClear, glDrawArrays и т.д.)
    glfwMakeContextCurrent(gWindow);

    // ============================================================
    // ШАГ 5: Регистрация callback'ов
    // ============================================================
    // glfwSetFramebufferSizeCallback регистрирует функцию, которая вызывается при изменении размера окна
    glfwSetFramebufferSizeCallback(gWindow, framebuffer_size_callback);

    // ============================================================
    // ШАГ 6: Начальная настройка viewport
    // ============================================================
    // Получаем реальный размер framebuffer (может отличаться от размера окна на Retina-дисплеях)
    int width, height;
    glfwGetFramebufferSize(gWindow, &width, &height);
    resize(width, height);  // настраиваем viewport и проекцию

    // ============================================================
    // ШАГ 7: Инициализация сцены
    // ============================================================
    // Загружаем текстуры, строим геометрию, настраиваем объекты сцены
    initScene();

    // ============================================================
    // ШАГ 8: Настройка глобальных состояний OpenGL
    // ============================================================

    // --- Z-буфер (depth buffer) ---
    // glEnable(GL_DEPTH_TEST) включает тест глубины
    // Без него дальние объекты будут рисоваться поверх ближних
    glEnable(GL_DEPTH_TEST);

    // --- Альфа-смешивание (transparency) ---
    // glEnable(GL_BLEND) включает смешивание цветов (для прозрачности)
    glEnable(GL_BLEND);

    // glBlendFunc задаёт формулу смешивания:
    // Result = Src * GL_SRC_ALPHA + Dst * GL_ONE_MINUS_SRC_ALPHA
    // Где Src = цвет нового фрагмента, Dst = цвет в буфере
    // Это стандартная формула для прозрачности
    glBlendFunc(GL_SRC_ALPHA, GL_ONE_MINUS_SRC_ALPHA);

    // --- Материалы из glColor ---
    // glEnable(GL_COLOR_MATERIAL) позволяет задавать материал через glColor
    // (упрощает код, но менее гибко, чем glMaterial)
    glEnable(GL_COLOR_MATERIAL);

    // glColorMaterial указывает, какие компоненты материала берутся из glColor
    // GL_AMBIENT_AND_DIFFUSE = цвет используется для ambient и diffuse компонент
    glColorMaterial(GL_FRONT_AND_BACK, GL_AMBIENT_AND_DIFFUSE);

    // --- Двустороннее освещение ---
    // glLightModeli(GL_LIGHT_MODEL_TWO_SIDE, GL_TRUE) включает освещение обеих сторон полигонов
    // Без этого задняя сторона полигонов будет чёрной
    glLightModeli(GL_LIGHT_MODEL_TWO_SIDE, GL_TRUE);

    // --- Модель затенения ---
    // glShadeModel(GL_SMOOTH) включает сглаженное затенение (Gouraud shading)
    // Цвета интерполируются между вершинами треугольника
    // Альтернатива: GL_FLAT (каждый полигон одного цвета)
    glShadeModel(GL_SMOOTH);

    // --- Нормализация векторов нормалей ---
    // glEnable(GL_NORMALIZE) автоматически нормализует векторы нормалей после трансформаций
    // Нужно, если используются неравномерные масштабирования (glScalef)
    glEnable(GL_NORMALIZE);

    // --- Отсечение задних граней (face culling) ---
    // glDisable(GL_CULL_FACE) отключает отсечение
    // Рисуем обе стороны полигонов (важно для прозрачных объектов)
    glDisable(GL_CULL_FACE);

    // --- Цвет фона ---
    // glClearColor(R, G, B, A) задаёт цвет для glClear(GL_COLOR_BUFFER_BIT)
    // Используется, если фоновая текстура не загрузилась
    glClearColor(1.f, 1.f, 1.f, 1.f);  // белый цвет

    // ============================================================
    // ШАГ 9: Настройка освещения (модель Фонга)
    // ============================================================

    // --- Включение освещения ---
    glEnable(GL_LIGHTING);  // включить систему освещения OpenGL

    // Включаем 3 источника света (GL_LIGHT0, GL_LIGHT1, GL_LIGHT2)
    // OpenGL поддерживает минимум 8 источников (GL_LIGHT0..GL_LIGHT7)
    glEnable(GL_LIGHT0);
    glEnable(GL_LIGHT1);
    glEnable(GL_LIGHT2);

    // --- Глобальный окружающий свет (global ambient) ---
    // Это базовый уровень освещённости, не зависящий от положения источников
    // Предотвращает абсолютно чёрные области в тени
    {
        GLfloat globalAmbient[4] = { 0.2f, 0.2f, 0.2f, 1.f };  // слабый серый свет
        glLightModelfv(GL_LIGHT_MODEL_AMBIENT, globalAmbient);
    }

    // ============================================================
    // Настройка параметров источников света
    // ============================================================
    // Модель освещения Фонга (Phong) состоит из 3 компонент для каждого источника:
    // - Ambient (окружающий) — базовая освещённость, не зависит от направления
    // - Diffuse (рассеянный) — зависит от угла между нормалью и направлением к источнику (Lambertian)
    // - Specular (зеркальный) — блики, зависят от угла отражения и направления к наблюдателю
    //
    // Формула: I = I_ambient + I_diffuse * (N·L) + I_specular * (R·V)^shininess
    // Где: N=нормаль, L=направление к свету, R=отражение, V=направление к камере
    //
    // Позиции источников устанавливаются каждый кадр в display() после трансформаций камеры
    {
        // ============================================================
        // LIGHT0 — Тёплый свет (основной, сверху справа спереди)
        // ============================================================
        // Позиция: (3, 3, 3) — правый верхний передний угол
        GLfloat dif0[4] = { 0.9f, 0.85f, 0.8f, 1.f };    // диффузный: тёплый белый
        GLfloat amb0[4] = { 0.10f, 0.10f, 0.10f, 1.f };  // окружающий: слабый серый
        GLfloat spc0[4] = { 0.7f, 0.7f, 0.7f, 1.f };     // зеркальный: яркие блики

        glLightfv(GL_LIGHT0, GL_DIFFUSE, dif0);
        glLightfv(GL_LIGHT0, GL_AMBIENT, amb0);
        glLightfv(GL_LIGHT0, GL_SPECULAR, spc0);

        // ============================================================
        // LIGHT1 — Холодный свет (контровой, сверху слева сзади)
        // ============================================================
        // Позиция: (-3, 3, -3) — левый верхний задний угол
        GLfloat dif1[4] = { 0.6f, 0.7f, 0.9f, 1.f };     // диффузный: холодный голубой
        GLfloat amb1[4] = { 0.05f, 0.05f, 0.08f, 1.f };  // окружающий: очень слабый голубоватый
        GLfloat spc1[4] = { 0.3f, 0.3f, 0.4f, 1.f };     // зеркальный: слабые голубоватые блики

        glLightfv(GL_LIGHT1, GL_DIFFUSE, dif1);
        glLightfv(GL_LIGHT1, GL_AMBIENT, amb1);
        glLightfv(GL_LIGHT1, GL_SPECULAR, spc1);

        // ============================================================
        // LIGHT2 — Фоновый свет (заполняющий, снизу сзади)
        // ============================================================
        // Позиция: (0, -3, 3) — внизу по центру сзади
        GLfloat dif2[4] = { 0.5f, 0.5f, 0.5f, 1.f };     // диффузный: нейтральный серый
        GLfloat amb2[4] = { 0.03f, 0.03f, 0.03f, 1.f };  // окружающий: очень слабый
        GLfloat spc2[4] = { 0.6f, 0.6f, 0.6f, 1.f };     // зеркальный: средние блики

        glLightfv(GL_LIGHT2, GL_DIFFUSE, dif2);
        glLightfv(GL_LIGHT2, GL_AMBIENT, amb2);
        glLightfv(GL_LIGHT2, GL_SPECULAR, spc2);
    }

    // ============================================================
    // ШАГ 10: Главный цикл рендеринга
    // ============================================================
    // Цикл выполняется пока окно не закрыто (пользователь не нажал ESC или кнопку закрытия)
    // glfwWindowShouldClose возвращает true, если окно должно быть закрыто
    while (!glfwWindowShouldClose(gWindow)) {

        // --- Обработка событий GLFW ---
        // glfwPollEvents обрабатывает все события (клавиатура, мышь, изменение размера и т.д.)
        // Вызывает зарегистрированные callback'и
        glfwPollEvents();

        // --- Обработка клавиш Space и R ---
        // (с edge detection для однократного срабатывания)
        processKeyCallbacks();

        // --- Отрисовка кадра ---
        // Рисуем всю сцену (фон, оси, астроида)
        display();

        // --- Обмен буферов (double buffering) ---
        // glfwSwapBuffers меняет местами front buffer (отображается на экране)
        // и back buffer (в который рисовали)
        // Это предотвращает мерцание (пользователь всегда видит готовый кадр)
        glfwSwapBuffers(gWindow);
    }

    // ============================================================
    // ШАГ 11: Очистка ресурсов и завершение
    // ============================================================

    // Уничтожить окно и освободить связанные ресурсы
    glfwDestroyWindow(gWindow);

    // Завершить работу GLFW и освободить все ресурсы
    glfwTerminate();

    return 0;  // успешное завершение
}
